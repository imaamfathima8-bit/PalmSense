import streamlit as st

from palmsense import llm
from palmsense.config import load_settings
from palmsense.palm_lines import NAMES, compare_hands, read_palm
from palmsense.pipeline import analyze_palm
from palmsense.ui import PHOTO_TIPS, disclaimer, hero, image_input, pill, result_banner, section, stage_gallery

STATUS_PILL = {"Detected": "ok", "Uncertain": "mid", "Not clearly visible": "no"}


def _line_table(feats: dict) -> str:
    rows = ["<table style='width:100%;border-collapse:collapse;font-size:.9rem'>"]
    for key in ("heart", "head", "life", "fate"):
        info = feats["lines"][key]
        a = info.get("attributes", {})
        desc = ", ".join(str(a[k]) for k in ("length", "shape", "clarity", "ending", "slope", "arc") if k in a) or "—"
        bar = int(info["confidence"] * 100)
        rows.append(
            f"<tr style='border-bottom:1px solid rgba(255,255,255,.07)'>"
            f"<td style='padding:8px 4px;font-weight:700'>{NAMES[key]}</td>"
            f"<td>{pill(info['status'], STATUS_PILL[info['status']])}</td>"
            f"<td style='width:90px'><div style='background:rgba(255,255,255,.08);border-radius:6px;height:7px'>"
            f"<div style='width:{bar}%;height:7px;border-radius:6px;background:linear-gradient(90deg,#8B5CF6,#22D3EE)'>"
            f"</div></div><small>{bar}%</small></td>"
            f"<td style='color:#AAB2C8;padding-left:10px'>{desc}</td></tr>")
    s = feats["palm_shape"]
    rows.append(f"<tr><td style='padding:8px 4px;font-weight:700'>Palm shape</td><td>{pill(s['element_type'] + ' hand', 'cv')}</td>"
                f"<td></td><td style='color:#AAB2C8;padding-left:10px'>{s['palm']} palm, {s['fingers']} fingers ({s['note']})</td></tr>")
    rows.append("</table>")
    return "".join(rows)


def render():
    settings = load_settings()
    hero("AI Palm Reading", "Read both palms",
         "Upload your left and right palm. Computer vision finds the visible lines; then a palmistry-specialised "
         "AI (Retrieval-Augmented Generation) writes a traditional reading. Just for fun!")
    disclaimer(llm.DISCLAIMER)
    st.caption(PHOTO_TIPS)

    cl, cr = st.columns(2, gap="large")
    with cl:
        section("🫲 Left palm")
        left_bytes = image_input("Left palm source", "left")
        if left_bytes:
            st.image(left_bytes, width=220)
    with cr:
        section("🫱 Right palm")
        right_bytes = image_input("Right palm source", "right")
        if right_bytes:
            st.image(right_bytes, width=220)

    if st.button("🔍 Analyse both palms", type="primary", width="stretch",
                 disabled=not (left_bytes and right_bytes)):
        with st.spinner("Enhancing images and detecting palm lines…"):
            la = analyze_palm(left_bytes, "left", settings)
            ra = analyze_palm(right_bytes, "right", settings)
        bad = [(n, a) for n, a in (("Left", la), ("Right", ra)) if not a.ok]
        if bad:
            for n, a in bad:
                result_banner("warn", f"{n} palm: Invalid Image", a.reason + " Please replace this photo.")
            st.session_state.pop("reading", None)
            return
        lr, rr = read_palm(la), read_palm(ra)
        st.session_state["reading"] = {
            "left": lr, "right": rr, "left_stages": la.stages, "right_stages": ra.stages,
            "differences": compare_hands(lr["features"], rr["features"]), "report": None,
        }
        st.session_state["chat_history"] = []

    rd = st.session_state.get("reading")
    if not rd:
        return

    section("👁 Observed by computer vision", "Lines drawn solid = detected · dashed with '?' = uncertain")
    a, b = st.columns(2, gap="large")
    for col, side in ((a, "left"), (b, "right")):
        with col:
            st.image(rd[side]["annotated"], caption=f"{side.title()} palm - annotated", width="stretch")
            st.markdown(_line_table(rd[side]["features"]), unsafe_allow_html=True)

    section("⚖️ Left vs right (measured)")
    for d in rd["differences"]:
        st.markdown(f"- {d}")

    with st.expander("🔬 Image-processing stages (left & right)"):
        t1, t2 = st.tabs(["Left palm", "Right palm"])
        with t1:
            stage_gallery(rd["left_stages"], cols=4)
        with t2:
            stage_gallery(rd["right_stages"], cols=4)

    section("✨ Interpreted by AI (palmistry tradition)")
    if st.button("🪄 Generate palm reading report", type="primary"):
        with st.spinner("Retrieving palmistry knowledge and writing your reading…"):
            rd["report"] = llm.generate_report(rd["left"]["features"], rd["right"]["features"], rd["differences"])
    rep = rd.get("report")
    if rep:
        st.markdown(pill(f"Generated by: {rep['source']}", "ai"), unsafe_allow_html=True)
        if rep.get("error"):
            st.caption(f"Online model failed, offline engine used instead: {rep['error'][:200]}")
        with st.container(border=True):
            st.markdown(rep["markdown"].replace("\n## ", "\n#### ").replace("## ", "#### ", 1))
        with st.expander(f"📚 Knowledge retrieved for this reading (RAG) - {len(rep['knowledge'])} entries"):
            for e in rep["knowledge"]:
                st.markdown(f"`{e['id']}` **{e['line']} / {e['section']}** - {e['text']}")
        st.download_button("⬇️ Download report (.md)", rep["markdown"], file_name="palm_reading_report.md")
        st.info("Open **Ask PalmSense** in the sidebar to chat about this reading.", icon="💬")
